import { existsSync } from "node:fs";
import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { releases } from "../src/updates/releases.js";

const root = fileURLToPath(new URL("../", import.meta.url));
const updatesDir = join(root, "updates");
const marker = "<!-- generated by scripts/sync-update-pages.mjs -->";

function escapeHtml(value) {
  return value
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;");
}

function pageHtml(release) {
  const title = escapeHtml(`${release.date} · ${release.title}`);
  const description = escapeHtml(`Mirally 更新日志：${release.title}。`);
  return `<!doctype html>
${marker}
<html lang="zh-CN">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <meta name="theme-color" content="#f6f8f7" />
    <meta name="description" content="${description}" />
    <meta property="og:title" content="${title} — Mirally 更新日志" />
    <meta property="og:description" content="${description}" />
    <meta property="og:type" content="article" />
    <link rel="icon" type="image/png" href="../../mirally.png" />
    <title>${title} — Mirally 更新日志</title>
  </head>
  <body>
    <div id="root"></div>
    <script type="module" src="/src/updates/main.jsx"></script>
  </body>
</html>
`;
}

for (const release of releases) {
  const dir = join(updatesDir, release.slug);
  await mkdir(dir, { recursive: true });
  await writeFile(join(dir, "index.html"), pageHtml(release), "utf8");
  console.log(`update page: updates/${release.slug}/index.html`);
}

const slugs = new Set(releases.map((release) => release.slug));
for (const entry of await readdir(updatesDir, { withFileTypes: true })) {
  if (!entry.isDirectory() || slugs.has(entry.name)) continue;
  const file = join(updatesDir, entry.name, "index.html");
  if (!existsSync(file)) continue;
  const html = await readFile(file, "utf8");
  if (!html.includes(marker)) continue;
  await rm(join(updatesDir, entry.name), { recursive: true, force: true });
  console.log(`removed stale update page: updates/${entry.name}`);
}
